export function cellAt(layer: LayerId, lane: LaneId): StackCell | undefined {
  return CELLS.find((c) => c.layer === layer && c.lane === lane);
}

export function cellsForLane(lane: LaneId): StackCell[] {
  return CELLS.filter((c) => c.lane === lane);
}

export function cellsForLayer(layer: LayerId): StackCell[] {
  return CELLS.filter((c) => c.layer === layer);
}
